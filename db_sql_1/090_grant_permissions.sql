GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA auth TO pulse_platform_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA auth TO pulse_platform_app;
REVOKE EXECUTE ON ALL FUNCTIONS IN SCHEMA auth FROM PUBLIC;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA auth TO pulse_platform_app;
ALTER DEFAULT PRIVILEGES FOR ROLE pulse_platform_owner IN SCHEMA auth GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO pulse_platform_app;
ALTER DEFAULT PRIVILEGES FOR ROLE pulse_platform_owner IN SCHEMA auth GRANT USAGE, SELECT ON SEQUENCES TO pulse_platform_app;
ALTER DEFAULT PRIVILEGES FOR ROLE pulse_platform_owner IN SCHEMA auth REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE pulse_platform_owner IN SCHEMA auth GRANT EXECUTE ON FUNCTIONS TO pulse_platform_app;

