-- Только новая установка. Запустить файл целиком в pulse_platform.
BEGIN;
DO $$ BEGIN
    IF current_database() <> 'pulse_platform' THEN
        RAISE EXCEPTION 'Подключитесь к pulse_platform';
    END IF;
END $$;
SET LOCAL ROLE pulse_platform_owner;
SET LOCAL search_path = public, pg_catalog;

REVOKE ALL ON DATABASE pulse_platform FROM PUBLIC;
GRANT CONNECT ON DATABASE pulse_platform TO pulse_platform_app, pulse_platform_readonly;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO pulse_platform_app;

REVOKE ALL ON SCHEMA auth FROM PUBLIC;
