package ru.agroeco.pulse.platform.domain.event;

import lombok.Getter;
import lombok.RequiredArgsConstructor;

import java.util.Arrays;
import java.util.Optional;

@Getter
@RequiredArgsConstructor
public enum DomainEventType {

    // ---- auth ----
    USER_AUTHENTICATED("USER_AUTHENTICATED"),
    USER_AUTHENTICATION_FAILED("USER_AUTHENTICATION_FAILED"),
    USER_LOGGED_OUT("USER_LOGGED_OUT"),

    // ---- user management ----
    USER_CREATED("USER_CREATED"),
    USER_ROLE_CHANGED("USER_ROLE_CHANGED"),
    USER_DISABLED("USER_DISABLED"),

    // ---- incident ----
    INCIDENT_CREATED("INCIDENT_CREATED"),
    INCIDENT_STATUS_CHANGED("INCIDENT_STATUS_CHANGED"),
    INCIDENT_COMMENT_ADDED("INCIDENT_COMMENT_ADDED"),
    INCIDENT_UPDATED("INCIDENT_UPDATED"),
    INCIDENT_CHECKPOINT_ADDED("INCIDENT_CHECKPOINT_ADDED"),
    INCIDENT_CHECKPOINT_REMOVED("INCIDENT_CHECKPOINT_REMOVED"),
    INCIDENT_MATERIAL_UPLOADED("INCIDENT_MATERIAL_UPLOADED"),
    INCIDENT_MATERIAL_DELETED("INCIDENT_MATERIAL_DELETED"),
    INCIDENT_MATERIAL_DOWNLOADED("INCIDENT_MATERIAL_DOWNLOADED"),
    OBJECT_REPORT_EXPORTED("OBJECT_REPORT_EXPORTED"),
    INCIDENT_CATEGORY_CREATED("INCIDENT_CATEGORY_CREATED"),
    INCIDENT_CATEGORY_UPDATED("INCIDENT_CATEGORY_UPDATED"),
    INCIDENT_CATEGORY_DELETED("INCIDENT_CATEGORY_DELETED"),
    INCIDENT_CATEGORY_RESTORED("INCIDENT_CATEGORY_RESTORED"),
    INCIDENT_CHECKLIST_ITEM_CREATED("INCIDENT_CHECKLIST_ITEM_CREATED"),
    INCIDENT_CHECKLIST_ITEM_UPDATED("INCIDENT_CHECKLIST_ITEM_UPDATED"),
    INCIDENT_CHECKLIST_ITEM_DELETED("INCIDENT_CHECKLIST_ITEM_DELETED"),
    INCIDENT_CHECKLIST_ITEM_RESTORED("INCIDENT_CHECKLIST_ITEM_RESTORED"),

    // ---- videoserver ----
    VIDEO_EVENT_INGESTED("VIDEO_EVENT_INGESTED"),

    // ---- refs: facilities (ref.objects) ----
    FACILITY_CREATED("FACILITY_CREATED"),

    // ---- refs: zones ----
    ZONE_CREATED("ZONE_CREATED"),

    // ---- refs: departments ----
    DEPARTMENT_CREATED("DEPARTMENT_CREATED"),

    // ---- refs: employees ----
    EMPLOYEE_CREATED("EMPLOYEE_CREATED"),

    // ---- trassir integration (внутренний IPC, в Kafka не идут) ----
    TRASSIR_OBJECTS_SNAPSHOT_RECEIVED("TRASSIR_OBJECTS_SNAPSHOT_RECEIVED"),
    TRASSIR_VIDEO_EVENT_RECEIVED("TRASSIR_VIDEO_EVENT_RECEIVED")

    ;

    private final String value;

    public static Optional<DomainEventType> fromValue(String value) {
        if (value == null) return Optional.empty();
        return Arrays.stream(values())
                .filter(a -> a.value.equals(value))
                .findFirst();
    }
}
